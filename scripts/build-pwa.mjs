import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve, relative, sep } from "node:path";

// Run after next build: cache exactly this release's chunks, never API responses.
const root = resolve(import.meta.dirname, "..");
async function files(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  return (await Promise.all(entries.map(entry => entry.isDirectory()
    ? files(resolve(dir, entry.name)) : [resolve(dir, entry.name)]))).flat();
}
const buildId = (await readFile(resolve(root, ".next/BUILD_ID"), "utf8")).trim();
const staticRoot = resolve(root, ".next/static");
const chunks = (await files(staticRoot)).filter(path => !path.endsWith(".map"))
  .map(path => "/_next/static/" + relative(staticRoot, path).split(sep).join("/"));
const assets = ["/", "/export", "/offline.html", "/manifest.webmanifest", "/favicon.svg",
  "/icons/icon-192.png", "/icons/icon-512.png", "/icons/icon-maskable-512.png",
  "/icons/apple-touch-icon.png", "/fonts/Jua-Regular.ttf", "/fonts/NanumMyeongjo-Regular.ttf",
  "/boannyang-3d.png", "/boannyang-thinking.png", "/network-security-original.pdf", ...chunks];
await writeFile(resolve(root, "public/pwa-precache.js"),
  `// Generated by scripts/build-pwa.mjs. Do not edit.\nself.__PWA_BUILD = ${JSON.stringify(buildId)};\nself.__PWA_ASSETS = ${JSON.stringify(assets)};\n`);
console.log(`PWA: prepared ${assets.length} offline resources for this build.`);
